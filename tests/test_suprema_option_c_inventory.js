'use strict';
const assert = require('node:assert/strict');
const C = require('../services/suprema/option-c-inventory');
const blank = () => ({escort:{},invasion:{},reserve:{}});
const fleet = {lightFighter:4002,heavyFighter:20,cruiser:1,battleship:0,bomber:0};
const empty = blank();
assert.equal(C.ONLINE_CAPACITY,4000);
assert.equal(C.inventory(empty),0);
const loaded = C.planLoad(fleet,empty,'lightFighter',4000);
assert.equal(loaded.usedSlots,4000);
assert.equal(loaded.planetFleet.lightFighter,2);
assert.equal(loaded.hangar.reserve.lightFighter,4000);
assert.equal(fleet.lightFighter,4002);
assert.deepEqual(empty,blank());
assert.throws(()=>C.planLoad(fleet,loaded.hangar,'lightFighter',1),/pieno/);
assert.throws(()=>C.planLoad(fleet,empty,'lightFighter',4003),/insufficienti/);
assert.throws(()=>C.planLoad(fleet,empty,'lightFighter',-1),/non valido/);
assert.throws(()=>C.planLoad(fleet,empty,'lightFighter',0),/nulla/);
assert.throws(()=>C.planLoad(fleet,empty,'lightFighter',1.5),/non valido/);
assert.throws(()=>C.planLoad(fleet,empty,'deathstar',1),/non autorizzata/);
assert.throws(()=>C.inventory({escort:{},invasion:{},reserve:{bomber:182}}),/superata/);
assert.throws(()=>C.inventory({escort:{},invasion:{},reserve:{bomber:-1}}),/non valido/);
assert.throws(()=>C.inventory({escort:{},invasion:{},reserve:{unknown:1}}),/sconosciuta/);
assert.throws(()=>C.inventory({escort:{},invasion:{}}),/mancante/);
const mixed = {escort:{heavyFighter:5},invasion:{cruiser:2},reserve:{bomber:1}};
assert.equal(C.inventory(mixed),53);
const after = C.planLoad({heavyFighter:1},mixed,'heavyFighter',1);
assert.equal(after.usedSlots,56);
assert.equal(after.hangar.reserve.heavyFighter,1);
assert.equal(C.inventory(mixed),53);
assert.equal(C.inventory(after.hangar),56);
console.log('Opzione C inventory: 20 assertions passed');
